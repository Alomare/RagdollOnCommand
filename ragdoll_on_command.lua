-- Key: Mod Bindings Menu (it may load before or after this addon)

local key = {registered = false, down = false, warned = false}

local function key_pressed()
    local menu = rawget(_G, 'ModBindingsMenu')
    if not (type(menu) == 'table' and menu.api == 1) then
        if not key.warned and M.frames > 600 then
            key.warned = true
            note('Mod Bindings Menu not found')
            write_status({'WAITING - Mod Bindings Menu is not installed or not loaded; no key to press',
                          'Ragdoll On Command ' .. M.version})
        end
        return false
    end
    if not key.registered then
        key.registered = true
        local ok, res, why = pcall(menu.register_binding, BINDING, host_text(menu, 'binding.ragdoll', 64), nil,
                                   {category = host_text(menu, 'option.mod', 64)})
        note('Mod Bindings Menu binding: ' .. ((ok and res) and 'registered' or
             ('not registered (' .. tostring(ok and why or res) .. ')')))
        if ok and res and M.ready then
            write_status({'OK - set the Ragdoll key in Options > Controls > MODS', 'Ragdoll On Command ' .. M.version})
        end
    end
    local ok, down = pcall(menu.is_down, BINDING)
    down = ok and down and true or false
    local edge = down and not key.down
    key.down = down
    return edge
end

