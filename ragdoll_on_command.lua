-- Ragdoll

local watch = nil  -- a ragdoll we started: {entity, since}

local function ragdoll()
    local a, why = local_avatar()
    if not a then note('Ragdoll key: ' .. why); return end
    if fn.is_ragdolled(a.state) ~= 0 then note('Ragdoll key: already ragdolled'); return end
    if fn.can_ragdoll(a.state) == 0 then note('Ragdoll key: not allowed right now (' .. flags_text(a) .. ')'); return end
    note(string.format('Ragdoll key: starting (entity %d, avatar %d, %s)', a.entity, a.index, flags_text(a)))
    fn.start_ragdoll(a.state, 0)
    local now = fn.is_ragdolled(a.state) ~= 0
    note(now and 'Ragdolled' or 'Started, but not ragdolled (' .. flags_text(a) .. ')')
    if now then watch = {entity = a.entity, since = M.frames} end
end

-- Logs how long a ragdoll we started lasts (reads only; the game ends it).
local function watch_step()
    if not watch or M.frames % WATCH_EVERY ~= 0 then return end
    local a = local_avatar()
    local still
    if a and a.entity == watch.entity then still = ragdoll_flag(a) end
    if still and M.frames - watch.since < WATCH_FRAMES then return end
    note(string.format('Ragdoll %s after %d frames', still and 'still on, no longer watched' or
                       (a and a.entity == watch.entity and 'ended' or 'Helldiver gone'), M.frames - watch.since))
    watch = nil
end

